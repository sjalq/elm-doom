#!/usr/bin/env python3
"""Write the Elm modules that are pure data in the C source.

    python3 tools/generate.py <linuxdoom-1.10 dir> <src dir>

Reads info.c (sprites, states, thing types), sounds.c (sound effects), tables.c
(fine sine, tangent and arctangent tables) and d_items.c (weapons), and writes
Doom/Info/{Sprite,Action,State,MobjType,Sfx,Weapon}.elm and Doom/Tables.elm. The
output is deterministic, so running it again on the same source changes nothing.

C names become Elm constructors in their own module, meant to be used qualified:
S_PLAY_RUN1 -> State.PlayRun1, MT_POSSESSED -> MobjType.Possessed,
SPR_TROO -> Sprite.Troo, sfx_pistol -> Sfx.Pistol, A_FireCGun -> Action.FireCGun.
"""

import os
import re
import sys

FRACUNIT = 65536

MOBJ_FLAGS = {
    "MF_SPECIAL": 1, "MF_SOLID": 2, "MF_SHOOTABLE": 4, "MF_NOSECTOR": 8,
    "MF_NOBLOCKMAP": 16, "MF_AMBUSH": 32, "MF_JUSTHIT": 64, "MF_JUSTATTACKED": 128,
    "MF_SPAWNCEILING": 256, "MF_NOGRAVITY": 512, "MF_DROPOFF": 0x400, "MF_PICKUP": 0x800,
    "MF_NOCLIP": 0x1000, "MF_SLIDE": 0x2000, "MF_FLOAT": 0x4000, "MF_TELEPORT": 0x8000,
    "MF_MISSILE": 0x10000, "MF_DROPPED": 0x20000, "MF_SHADOW": 0x40000,
    "MF_NOBLOOD": 0x80000, "MF_CORPSE": 0x100000, "MF_INFLOAT": 0x200000,
    "MF_COUNTKILL": 0x400000, "MF_COUNTITEM": 0x800000, "MF_SKULLFLY": 0x1000000,
    "MF_NOTDMATCH": 0x2000000, "MF_TRANSLATION": 0xC000000, "MF_TRANSSHIFT": 26,
}


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def camel(name, prefix):
    """S_PLAY_RUN1 -> PlayRun1 (prefix "S_" removed)."""
    assert name.startswith(prefix), (name, prefix)
    parts = name[len(prefix):].split("_")
    return "".join(p[:1].upper() + p[1:].lower() for p in parts if p)


def action_ctor(name):
    """A_FireCGun -> FireCGun, A_BFGsound -> BFGsound (keeps the C casing)."""
    assert name.startswith("A_"), name
    rest = name[2:]
    return rest[:1].upper() + rest[1:]


def braces_block(text, start_pattern):
    """The text between the braces that follow start_pattern."""
    m = re.search(start_pattern, text)
    assert m, start_pattern
    i = text.index("{", m.start())
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[i + 1:j]
    raise ValueError(start_pattern)


def eval_c(expr, names):
    expr = expr.strip()
    for k in sorted(names, key=len, reverse=True):
        expr = re.sub(r"\b%s\b" % re.escape(k), str(names[k]), expr)
    if not re.fullmatch(r"[0-9xXa-fA-F\s|*+()\-<>]+", expr):
        raise ValueError("can't evaluate C expression: " + expr)
    return int(eval(expr))


def header(module, exposing, doc, imports=()):
    lines = [
        "module %s exposing (%s)" % (module, exposing),
        "",
        "{-| " + doc.strip(),
        "",
        "Generated by tools/generate.py from id Software's linuxdoom-1.10 source",
        "(GPL-2.0-or-later). Don't edit by hand: change the generator and run it again.",
        "",
        "@docs " + ", ".join(x.replace("(..)", "").strip() for x in exposing.split(",")),
        "",
        "-}",
        "",
    ]
    for imp in imports:
        lines.append(imp)
    if imports:
        lines.append("")
    lines.append("")
    return lines


def elm_list(items, indent="    ", per_line=1):
    """An Elm list literal, elm-format style, items already rendered."""
    if not items:
        return [indent + "[]"]
    out = []
    for i in range(0, len(items), per_line):
        chunk = ", ".join(items[i:i + per_line])
        out.append(indent + ("[ " if i == 0 else ", ") + chunk)
    out.append(indent + "]")
    return out


def custom_type(name, ctors):
    lines = ["{-| One constructor per value of the C enum, in its order. -}", "type " + name]
    for i, c in enumerate(ctors):
        lines.append(("    = " if i == 0 else "    | ") + c)
    return lines


def write(path, lines):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(lines).rstrip() + "\n")


def index_functions(type_name, ctors, to_name, from_name, all_name):
    lines = [
        "",
        "",
        "{-| Its position in the C source's enum. -}",
        "%s : %s -> Int" % (to_name, type_name),
        "%s x =" % to_name,
        "    case x of",
    ]
    for i, c in enumerate(ctors):
        lines.append("        %s ->\n            %d\n" % (c, i))
    lines[-1] = lines[-1].rstrip()
    lines += [
        "",
        "",
        "{-| Every value, in the C source's order. -}",
        "%s : Array %s" % (all_name, type_name),
        "%s =" % all_name,
        "    Array.fromList",
    ]
    lines += elm_list(ctors, indent="        ", per_line=6)
    lines += [
        "",
        "",
        "{-| The value at a position in the C source's enum, if there is one. -}",
        "%s : Int -> Maybe %s" % (from_name, type_name),
        "%s i =" % from_name,
        "    Array.get i %s" % all_name,
    ]
    return lines


def main():
    csrc, out = sys.argv[1], sys.argv[2]
    info = strip_comments(open(os.path.join(csrc, "info.c"), encoding="latin-1").read())
    info_h = strip_comments(open(os.path.join(csrc, "info.h"), encoding="latin-1").read())
    sounds_c = strip_comments(open(os.path.join(csrc, "sounds.c"), encoding="latin-1").read())
    sounds_h = strip_comments(open(os.path.join(csrc, "sounds.h"), encoding="latin-1").read())
    tables_c = strip_comments(open(os.path.join(csrc, "tables.c"), encoding="latin-1").read())

    # ---- Sprites
    spr_enum = re.findall(r"\bSPR_\w+", braces_block(info_h, r"typedef\s+enum\s*\{[^}]*SPR_TROO"))
    spr_enum = [s for s in spr_enum if s != "SPR_TROO" or True]
    spr_names = re.findall(r'"(\w+)"', braces_block(info, r"char\s*\*\s*sprnames\s*\[\s*NUMSPRITES\s*\]\s*="))
    assert len(spr_enum) == len(spr_names), (len(spr_enum), len(spr_names))
    spr_ctors = [camel(s, "SPR_") for s in spr_enum]
    lines = header(
        "Doom.Info.Sprite",
        "Sprite(..), all, fromIndex, index, name",
        "The sprites things are drawn with (`spritenum_t`, `sprnames`).",
        ["import Array exposing (Array)"],
    )
    lines += custom_type("Sprite", spr_ctors)
    lines += index_functions("Sprite", spr_ctors, "index", "fromIndex", "all")
    lines += [
        "",
        "",
        "{-| The four letters its lumps start with in the WAD (TROOA1 is TROO's frame A, angle 1). -}",
        "name : Sprite -> String",
        "name sprite =",
        "    case sprite of",
    ]
    for c, n in zip(spr_ctors, spr_names):
        lines.append('        %s ->\n            "%s"\n' % (c, n))
    write(os.path.join(out, "Doom/Info/Sprite.elm"), lines)

    # ---- States and actions
    state_enum = re.findall(r"\bS_\w+", braces_block(info_h, r"typedef\s+enum\s*\{\s*S_NULL"))
    state_enum = [s for s in state_enum if s != "NUMSTATES"]
    state_rows = re.findall(r"\{([^{}]*\{[^{}]*\}[^{}]*)\}", braces_block(info, r"state_t\s+states\s*\[\s*NUMSTATES\s*\]\s*="))
    assert len(state_rows) == len(state_enum), (len(state_rows), len(state_enum))
    state_ctor = {s: camel(s, "S_") for s in state_enum}
    actions = []
    states = []
    for row in state_rows:
        m = re.fullmatch(r"\s*(SPR_\w+)\s*,\s*([^,]+),\s*([^,]+),\s*\{\s*(\w+)\s*\}\s*,\s*(S_\w+)\s*,\s*([^,]+),\s*([^,]+)\s*", row)
        assert m, row
        spr, frame, tics, act, nxt, m1, m2 = m.groups()
        frame_v = eval_c(frame, {"FF_FULLBRIGHT": 0x8000})
        act_v = None if act in ("NULL", "0") else act
        if act_v and act_v not in actions:
            actions.append(act_v)
        states.append((spr, frame_v, eval_c(tics, {}), act_v, nxt, eval_c(m1, {}), eval_c(m2, {})))

    action_ctors = [action_ctor(a) for a in actions]
    lines = header(
        "Doom.Info.Action",
        "Action(..), name",
        """What a state does when a thing or weapon enters it (the C source's `A_` functions).
Doom.Play.Action runs them; this module only names them, so the state table can say
which one goes with each state without depending on the game's code.""",
    )
    lines += custom_type("Action", action_ctors)
    lines += [
        "",
        "",
        "{-| The C function's name, for logs. -}",
        "name : Action -> String",
        "name action =",
        "    case action of",
    ]
    for c, a in zip(action_ctors, actions):
        lines.append('        %s ->\n            "%s"\n' % (c, a))
    write(os.path.join(out, "Doom/Info/Action.elm"), lines)

    ctors = [state_ctor[s] for s in state_enum]
    lines = header(
        "Doom.Info.State",
        "State(..), Def, all, def, fromIndex, index",
        """The state table (`statenum_t`, `states[]`): every frame of every animation, how
long it lasts, what it does and which state follows it.""",
        [
            "import Array exposing (Array)",
            "import Doom.Info.Action as Action exposing (Action)",
            "import Doom.Info.Sprite as Sprite exposing (Sprite)",
        ],
    )
    lines += custom_type("State", ctors)
    lines += index_functions("State", ctors, "index", "fromIndex", "all")
    lines += [
        "",
        "",
        "{-| One row of `states[]`. `frame` keeps C's FF_FULLBRIGHT bit (0x8000); `tics` is -1",
        "for a state that lasts forever. -}",
        "type alias Def =",
        "    { sprite : Sprite",
        "    , frame : Int",
        "    , tics : Int",
        "    , action : Maybe Action",
        "    , next : State",
        "    , misc1 : Int",
        "    , misc2 : Int",
        "    }",
        "",
        "",
        "{-| The row for a state. -}",
        "def : State -> Def",
        "def state =",
        "    case Array.get (index state) defs of",
        "        Just d ->",
        "            d",
        "",
        "        Nothing ->",
        "            -- Unreachable: defs has a row for every State, in index order.",
        "            { sprite = Sprite.Troo, frame = 0, tics = -1, action = Nothing, next = Null, misc1 = 0, misc2 = 0 }",
        "",
        "",
        "defs : Array Def",
        "defs =",
        "    Array.fromList",
    ]
    rows = []
    for spr, frame_v, tics_v, act_v, nxt, m1, m2 in states:
        act_s = "Nothing" if act_v is None else "Just Action." + action_ctor(act_v)
        rows.append(
            "{ sprite = Sprite.%s, frame = %d, tics = %d, action = %s, next = %s, misc1 = %d, misc2 = %d }"
            % (camel(spr, "SPR_"), frame_v, tics_v, act_s, state_ctor[nxt], m1, m2)
        )
    lines += elm_list(rows, indent="        ")
    write(os.path.join(out, "Doom/Info/State.elm"), lines)

    # ---- Sound effects
    sfx_enum = re.findall(r"\bsfx_\w+", braces_block(sounds_h, r"typedef\s+enum\s*\{\s*sfx_None"))
    sfx_enum = [s for s in sfx_enum if s != "NUMSFX"]
    sfx_rows = re.findall(r"\{([^{}]*)\}", braces_block(sounds_c, r"sfxinfo_t\s+S_sfx\s*\[\s*\]\s*="))
    assert len(sfx_rows) == len(sfx_enum), (len(sfx_rows), len(sfx_enum))
    sfx_ctor = {s: camel(s, "sfx_") for s in sfx_enum}
    sfx_ctor["sfx_None"] = "None"
    sfx_info = []
    for row in sfx_rows:
        parts = [p.strip() for p in row.split(",")]
        name = parts[0].strip('"')
        singular = parts[1] == "true"
        priority = int(parts[2])
        link = parts[3]
        pitch, volume = int(parts[4]), int(parts[5])
        if link in ("0", "NULL"):
            link_ctor = "Nothing"
        else:
            lm = re.fullmatch(r"&\s*S_sfx\s*\[\s*(sfx_\w+)\s*\]", link)
            assert lm, link
            link_ctor = "Just " + sfx_ctor[lm.group(1)]
        sfx_info.append((name, singular, priority, link_ctor, pitch, volume))
    ctors = [sfx_ctor[s] for s in sfx_enum]
    lines = header(
        "Doom.Info.Sfx",
        "Sfx(..), Info, all, fromIndex, index, info",
        """Sound effects (`sfxenum_t`, `S_sfx[]`). The lump for `Pistol` is DSPISTOL.""",
        ["import Array exposing (Array)"],
    )
    lines += custom_type("Sfx", ctors)
    lines += index_functions("Sfx", ctors, "index", "fromIndex", "all")
    lines += [
        "",
        "",
        "{-| A row of `S_sfx[]`: the lump name without DS, whether only one may play at a time,",
        "its priority, and the sound it is a variant of (`link`), with the pitch and volume",
        "the variant plays at (-1 for the sound's own). -}",
        "type alias Info =",
        "    { name : String, singular : Bool, priority : Int, link : Maybe Sfx, pitch : Int, volume : Int }",
        "",
        "",
        "{-| Its row. -}",
        "info : Sfx -> Info",
        "info sfx =",
        "    case sfx of",
    ]
    for c, (name, singular, priority, link_ctor, pitch, volume) in zip(ctors, sfx_info):
        lines.append(
            '        %s ->\n            { name = "%s", singular = %s, priority = %d, link = %s, pitch = %d, volume = %d }\n'
            % (c, name, "True" if singular else "False", priority, link_ctor, pitch, volume)
        )
    write(os.path.join(out, "Doom/Info/Sfx.elm"), lines)

    # ---- Thing types
    mt_enum = re.findall(r"\bMT_\w+", braces_block(info_h, r"typedef\s+enum\s*\{\s*MT_PLAYER"))
    mt_enum = [s for s in mt_enum if s != "NUMMOBJTYPES"]
    mt_rows = re.findall(r"\{([^{}]*)\}", braces_block(info, r"mobjinfo_t\s+mobjinfo\s*\[\s*NUMMOBJTYPES\s*\]\s*="))
    assert len(mt_rows) == len(mt_enum), (len(mt_rows), len(mt_enum))
    fields = [
        ("doomednum", "int"), ("spawnstate", "state"), ("spawnhealth", "int"), ("seestate", "state"),
        ("seesound", "sfx"), ("reactiontime", "int"), ("attacksound", "sfx"), ("painstate", "state"),
        ("painchance", "int"), ("painsound", "sfx"), ("meleestate", "state"), ("missilestate", "state"),
        ("deathstate", "state"), ("xdeathstate", "state"), ("deathsound", "sfx"), ("speed", "int"),
        ("radius", "int"), ("height", "int"), ("mass", "int"), ("damage", "int"),
        ("activesound", "sfx"), ("flags", "int"), ("raisestate", "state"),
    ]
    mt_ctors = [camel(s, "MT_") for s in mt_enum]
    lines = header(
        "Doom.Info.MobjType",
        "Info, MobjType(..), all, fromIndex, index, info",
        """The kinds of thing (`mobjtype_t`, `mobjinfo[]`). A state of `State.Null` or a sound
of `Sfx.None` means the thing has none. `speed`, `radius` and `height` are fixed-point
where the C source multiplies by FRACUNIT.""",
        [
            "import Array exposing (Array)",
            "import Doom.Info.Sfx as Sfx exposing (Sfx)",
            "import Doom.Info.State as State exposing (State)",
        ],
    )
    lines += custom_type("MobjType", mt_ctors)
    lines += index_functions("MobjType", mt_ctors, "index", "fromIndex", "all")
    type_of = {"int": "Int", "state": "State", "sfx": "Sfx"}
    lines += ["", "", "{-| A row of `mobjinfo[]`. -}", "type alias Info ="]
    for i, (f, t) in enumerate(fields):
        lines.append(("    { " if i == 0 else "    , ") + "%s : %s" % (f, type_of[t]))
    lines += ["    }", "", "", "{-| Its row. -}", "info : MobjType -> Info", "info t =", "    case t of"]
    for c, row in zip(mt_ctors, mt_rows):
        vals = [v.strip() for v in row.split(",")]
        vals = [v for v in vals if v != ""]
        assert len(vals) == len(fields), (c, vals)
        rendered = []
        for (f, t), v in zip(fields, vals):
            if t == "state":
                rendered.append("%s = State.%s" % (f, "Null" if v == "0" else state_ctor[v]))
            elif t == "sfx":
                rendered.append("%s = Sfx.%s" % (f, "None" if v == "0" else sfx_ctor[v]))
            else:
                rendered.append("%s = %d" % (f, eval_c(v, dict(MOBJ_FLAGS, FRACUNIT=FRACUNIT))))
        lines.append("        %s ->" % c)
        lines.append("            { " + "\n            , ".join(rendered) + "\n            }\n")
    write(os.path.join(out, "Doom/Info/MobjType.elm"), lines)

    # ---- Tables
    def table(name, size):
        body = braces_block(tables_c, r"\b%s\s*\[\s*%d\s*\]\s*=" % (name, size))
        vals = [int(v, 0) for v in re.findall(r"-?(?:0x[0-9a-fA-F]+|\d+)", body)]
        assert len(vals) == size, (name, len(vals))
        return vals

    finetangent = table("finetangent", 4096)
    finesine = table("finesine", 10240)
    tantoangle = table("tantoangle", 2049)
    lines = header(
        "Doom.Tables",
        "finecosine, finesine, finetangent, tantoangle",
        """Doom's trigonometry tables (tables.c), exactly as the C source has them: the game's
results depend on their every bit, so they aren't computed.

  - `finesine i`: sine of fine angle i (8192 to a circle), fixed-point, for i from 0 to
    10239 (the table runs a quarter circle past a full one, so cosine can share it).
  - `finecosine i`: `finesine (i + 2048)`.
  - `finetangent i`: for i from 0 to 4095, angles from -90 to +90 degrees.
  - `tantoangle i`: the angle (BAM, unsigned) whose tangent is i / 2048, i from 0 to 2048.

Each returns 0 outside its range, where the C source would read past its array.""",
        ["import Array exposing (Array)"],
    )

    def table_fn(fname, values, doc):
        out_lines = [
            "",
            "",
            "{-| %s -}" % doc,
            "%s : Int -> Int" % fname,
            "%s i =" % fname,
            "    Maybe.withDefault 0 (Array.get i %sTable)" % fname,
            "",
            "",
            "%sTable : Array Int" % fname,
            "%sTable =" % fname,
            "    Array.fromList",
        ]
        out_lines += elm_list([str(v) for v in values], indent="        ", per_line=8)
        return out_lines

    lines += table_fn("finesine", finesine, "Sine of a fine angle, fixed-point.")
    lines += [
        "",
        "",
        "{-| Cosine of a fine angle, fixed-point: the sine table a quarter circle on. -}",
        "finecosine : Int -> Int",
        "finecosine i =",
        "    finesine (i + 2048)",
    ]
    lines += table_fn("finetangent", finetangent, "Tangent of a fine angle, fixed-point.")
    lines += table_fn("tantoangle", tantoangle, "The angle, unsigned BAM, whose tangent is i / 2048.")
    write(os.path.join(out, "Doom/Tables.elm"), lines)

    print("sprites %d, actions %d, states %d, sfx %d, thing types %d"
          % (len(spr_ctors), len(action_ctors), len(states), len(sfx_enum), len(mt_ctors)))


if __name__ == "__main__":
    main()
