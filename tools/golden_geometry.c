/* Golden vectors for the pure physics geometry, computed by linuxdoom-1.10's own code
   (copied below), printed as the Elm module tests/GoldenVectors.elm:

       cc -fwrapv -w -I <linuxdoom-1.10> tools/golden_geometry.c -o golden
       ./golden > tests/GoldenVectors.elm

   -fwrapv gives int overflow the wrap-around the game relies on. */
#include <stdio.h>
#include <stdlib.h>
#define MAXINT 2147483647
#define MININT (-2147483647 - 1)
#include "tables.c"

fixed_t FixedMul(fixed_t a, fixed_t b) { return ((long long)a * (long long)b) >> FRACBITS; }
fixed_t FixedDiv2(fixed_t a, fixed_t b) {
    double c = ((double)a) / ((double)b) * FRACUNIT;
    if (c >= 2147483648.0 || c < -2147483648.0) { fprintf(stderr, "div\n"); exit(1); }
    return (fixed_t)c;
}
fixed_t FixedDiv(fixed_t a, fixed_t b) {
    if ((abs(a) >> 14) >= abs(b)) return (a ^ b) < 0 ? MININT : MAXINT;
    return FixedDiv2(a, b);
}

typedef struct { fixed_t x, y, dx, dy; } divline_t;

angle_t R_PointToAngle(fixed_t x, fixed_t y) {
    if ((!x) && (!y)) return 0;
    if (x >= 0) {
        if (y >= 0) {
            if (x > y) return tantoangle[SlopeDiv(y, x)];
            else return ANG90 - 1 - tantoangle[SlopeDiv(x, y)];
        } else {
            y = -y;
            if (x > y) return -tantoangle[SlopeDiv(y, x)];
            else return ANG270 + tantoangle[SlopeDiv(x, y)];
        }
    } else {
        x = -x;
        if (y >= 0) {
            if (x > y) return ANG180 - 1 - tantoangle[SlopeDiv(y, x)];
            else return ANG90 + tantoangle[SlopeDiv(x, y)];
        } else {
            y = -y;
            if (x > y) return ANG180 + tantoangle[SlopeDiv(y, x)];
            else return ANG270 - 1 - tantoangle[SlopeDiv(x, y)];
        }
    }
    return 0;
}

fixed_t P_AproxDistance(fixed_t dx, fixed_t dy) {
    dx = abs(dx);
    dy = abs(dy);
    if (dx < dy) return dx + dy - (dx >> 1);
    return dx + dy - (dy >> 1);
}

int P_PointOnLineSide(fixed_t x, fixed_t y, divline_t *line) {
    fixed_t dx, dy, left, right;
    if (!line->dx) { if (x <= line->x) return line->dy > 0; return line->dy < 0; }
    if (!line->dy) { if (y <= line->y) return line->dx < 0; return line->dx > 0; }
    dx = (x - line->x);
    dy = (y - line->y);
    left = FixedMul(line->dy >> FRACBITS, dx);
    right = FixedMul(dy, line->dx >> FRACBITS);
    if (right < left) return 0;
    return 1;
}

int P_PointOnDivlineSide(fixed_t x, fixed_t y, divline_t *line) {
    fixed_t dx, dy, left, right;
    if (!line->dx) { if (x <= line->x) return line->dy > 0; return line->dy < 0; }
    if (!line->dy) { if (y <= line->y) return line->dx < 0; return line->dx > 0; }
    dx = (x - line->x);
    dy = (y - line->y);
    if ((line->dy ^ line->dx ^ dx ^ dy) & 0x80000000) {
        if ((line->dy ^ dx) & 0x80000000) return 1;
        return 0;
    }
    left = FixedMul(line->dy >> 8, dx >> 8);
    right = FixedMul(dy >> 8, line->dx >> 8);
    if (right < left) return 0;
    return 1;
}

int R_PointOnSide(fixed_t x, fixed_t y, divline_t *node) {
    fixed_t dx, dy, left, right;
    if (!node->dx) { if (x <= node->x) return node->dy > 0; return node->dy < 0; }
    if (!node->dy) { if (y <= node->y) return node->dx < 0; return node->dx > 0; }
    dx = (x - node->x);
    dy = (y - node->y);
    if ((node->dy ^ node->dx ^ dx ^ dy) & 0x80000000) {
        if ((node->dy ^ dx) & 0x80000000) return 1;
        return 0;
    }
    left = FixedMul(node->dy >> FRACBITS, dx);
    right = FixedMul(dy, node->dx >> FRACBITS);
    if (right < left) return 0;
    return 1;
}

fixed_t P_InterceptVector(divline_t *v2, divline_t *v1) {
    fixed_t frac, num, den;
    den = FixedMul(v1->dy >> 8, v2->dx) - FixedMul(v1->dx >> 8, v2->dy);
    if (den == 0) return 0;
    num = FixedMul((v1->x - v2->x) >> 8, v1->dy) + FixedMul((v2->y - v1->y) >> 8, v1->dx);
    frac = FixedDiv(num, den);
    return frac;
}

static unsigned long long seed = 12345;
static unsigned rnd32(void) {
    seed = seed * 6364136223846793005ULL + 1442695040888963407ULL;
    return (unsigned)(seed >> 32);
}
/* a mix of full-range int32s, map-sized values and small/edge values */
static int val(void) {
    unsigned k = rnd32() % 4;
    int v = (int)rnd32();
    if (k == 0) return v;
    if (k == 1) return v >> 4;
    if (k == 2) return (v >> 20) << 16;
    switch (rnd32() % 6) {
    case 0: return 0;
    case 1: return MININT;
    case 2: return MAXINT;
    case 3: return 1;
    case 4: return -1;
    default: return v >> 24;
    }
}

int main(void) {
    int i, n = 400;
    printf("module GoldenVectors exposing (angles, distances, lineSides, divlineSides, nodeSides, intercepts)\n\n");
    printf("{-| Results of linuxdoom-1.10's own R_PointToAngle2, P_AproxDistance, P_PointOnLineSide,\nP_PointOnDivlineSide, R_PointOnSide and P_InterceptVector on pseudo-random inputs\n(generated by tools/golden_geometry.c).\n-}\n\n\n");

    printf("angles : List ( List Int, Int )\nangles =\n    [ ");
    for (i = 0; i < n; i++) {
        int x = val(), y = val();
        printf("%s( [ %d, %d ], %u )\n", i ? "    , " : "", x, y, R_PointToAngle(x, y));
    }
    printf("    ]\n\n\n");

    printf("distances : List ( List Int, Int )\ndistances =\n    [ ");
    for (i = 0; i < n; i++) {
        int x = val(), y = val();
        printf("%s( [ %d, %d ], %d )\n", i ? "    , " : "", x, y, P_AproxDistance(x, y));
    }
    printf("    ]\n\n\n");

    const char *names[3] = {"lineSides", "divlineSides", "nodeSides"};
    int f;
    for (f = 0; f < 3; f++) {
        printf("%s : List ( List Int, Int )\n%s =\n    [ ", names[f], names[f]);
        for (i = 0; i < n; i++) {
            divline_t d;
            int x = val(), y = val(), r;
            d.x = val(); d.y = val(); d.dx = val(); d.dy = val();
            if (rnd32() % 8 == 0) d.dx = 0;
            if (rnd32() % 8 == 0) d.dy = 0;
            r = f == 0 ? P_PointOnLineSide(x, y, &d) : f == 1 ? P_PointOnDivlineSide(x, y, &d) : R_PointOnSide(x, y, &d);
            printf("%s( [ %d, %d, %d, %d, %d, %d ], %d )\n", i ? "    , " : "", x, y, d.x, d.y, d.dx, d.dy, r);
        }
        printf("    ]\n\n\n");
    }

    printf("intercepts : List ( List Int, Int )\nintercepts =\n    [ ");
    for (i = 0; i < n; i++) {
        divline_t a, b;
        a.x = val(); a.y = val(); a.dx = val(); a.dy = val();
        b.x = val(); b.y = val(); b.dx = val(); b.dy = val();
        /* FixedDiv2 stops the game where the quotient overflows; skip those */
        {
            fixed_t den = FixedMul(b.dy >> 8, a.dx) - FixedMul(b.dx >> 8, a.dy);
            fixed_t num = FixedMul((b.x - a.x) >> 8, b.dy) + FixedMul((a.y - b.y) >> 8, b.dx);
            if (den != 0 && !((abs(num) >> 14) >= abs(den))) {
                double c = ((double)num) / ((double)den) * FRACUNIT;
                if (c >= 2147483648.0 || c < -2147483648.0) { i--; continue; }
            }
        }
        printf("%s( [ %d, %d, %d, %d, %d, %d, %d, %d ], %d )\n", i ? "    , " : "",
               a.x, a.y, a.dx, a.dy, b.x, b.y, b.dx, b.dy, P_InterceptVector(&a, &b));
    }
    printf("    ]\n");
    return 0;
}
